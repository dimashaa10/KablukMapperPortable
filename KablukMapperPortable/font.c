const unsigned char *font_glyph(char c)
{
    int index;

    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A'); /* upper case only */
    }
    index = (int)(unsigned char)c - FONT_FIRST;
    if (index < 0 || index > (FONT_LAST - FONT_FIRST)) {
        index = 0; /* space */
    }
    return FONT_COLS[index];
}
